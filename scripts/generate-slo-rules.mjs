#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'monitoring/slo.yml'), 'utf8');
const config = YAML.parse(source);
const errors = [];
if (!config || config.version !== '1' || !Array.isArray(config.slos) || !config.slos.length) errors.push('monitoring/slo.yml: expected version 1 and a non-empty slos list');
const metricsSource = ['api/src/observability', 'services/aggregator/src/observability'].map((dir) => fs.readdirSync(path.join(root, dir)).filter((name) => name.endsWith('.ts')).map((name) => fs.readFileSync(path.join(root, dir, name), 'utf8')).join('\n')).join('\n');
const knownMetrics = new Set([...metricsSource.matchAll(/name:\s*['"]([a-zA-Z_:][a-zA-Z0-9_:]*)['"]/g)].map((match) => match[1]));
const names = new Set();
for (const slo of config.slos ?? []) {
  const label = `monitoring/slo.yml SLO ${slo.name ?? '<unnamed>'}`;
  if (!slo.name || names.has(slo.name)) errors.push(`${label}: missing or duplicate name`);
  names.add(slo.name);
  if (!(slo.target > 0 && slo.target < 100)) errors.push(`${label}: target must be between 0 and 100`);
  if (!/^\d+[smhd]$/.test(slo.window ?? '')) errors.push(`${label}: invalid window`);
  for (const key of ['good_events', 'total_events']) {
    const expr = slo.sli?.[key];
    if (typeof expr !== 'string' || !expr.trim()) { errors.push(`${label}: missing sli.${key}`); continue; }
    const metricTokens = expr.match(/[a-zA-Z_:][a-zA-Z0-9_:]*(?=\s*(?:\{|\[|\)|\/|$))/g) ?? [];
    for (const metric of metricTokens) if (!knownMetrics.has(metric) && !['_bucket', '_count', '_sum'].some((suffix) => metric.endsWith(suffix) && knownMetrics.has(metric.slice(0, -suffix.length)))) errors.push(`${label}: SLI metric ${metric} is not declared in the API or aggregator exporter registry`);
  }
  if (!slo.burn_rate?.fast || !slo.burn_rate?.slow) errors.push(`${label}: burn_rate.fast and burn_rate.slow are required`);
  else for (const tier of ['fast', 'slow']) {
    const policy = slo.burn_rate[tier];
    if (!/^\d+[smhd]$/.test(policy.window ?? '') || !(policy.threshold > 0) || !(policy.budget_percent > 0 && policy.budget_percent <= 100)) errors.push(`${label}: invalid burn_rate.${tier} window, threshold or budget_percent`);
  }
}
if (errors.length) { console.error(errors.map((error) => `FAIL ${error}`).join('\n')); process.exit(1); }
const groups = [];
for (const slo of config.slos) {
  const base = `stellar_slo:${slo.name}`;
  groups.push(`      - record: ${base}:good_events:rate5m\n        expr: ${slo.sli.good_events}\n      - record: ${base}:total_events:rate5m\n        expr: ${slo.sli.total_events}\n      - record: ${base}:error_ratio:rate5m\n        expr: 1 - (${base}:good_events:rate5m / clamp_min(${base}:total_events:rate5m, 1e-12))`);
  for (const tier of ['fast', 'slow']) {
    const p = slo.burn_rate[tier];
    const burnThreshold = Number((((100 - slo.target) / 100) * p.threshold).toFixed(8));
    groups.push(`      - alert: ${slo.name[0].toUpperCase()}${slo.name.slice(1).replace(/-([a-z])/g, (_, c) => c.toUpperCase())}${tier === 'fast' ? 'Fast' : 'Slow'}Burn\n        expr: ${base}:error_ratio:rate5m > ${burnThreshold}\n        for: ${p.window}\n        labels:\n          severity: ${tier === 'fast' ? 'critical' : 'warning'}\n          slo: ${slo.name}\n        annotations:\n          summary: ${slo.name} error budget burn is above ${p.threshold}x\n          budget_exhaustion: ${p.budget_percent}%`);
  }
}
const output = `# Generated by scripts/generate-slo-rules.mjs from monitoring/slo.yml; do not edit.\napiVersion: monitoring.coreos.com/v1\nkind: PrometheusRule\nmetadata:\n  name: stellar-oracle-slos\n  labels:\n    app: stellar-price-oracle\nspec:\n  groups:\n    - name: stellar-oracle-slos\n      interval: 1m\n      rules:\n${groups.map((group) => group.split('\n').map((line) => `        ${line.slice(6)}`).join('\n')).join('\n')}\n`;
const destination = path.join(root, 'k8s/base/generated-slo-rules.yaml');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) { console.error('FAIL k8s/base/generated-slo-rules.yaml: stale; run npm run generate:slo-rules'); process.exit(1); }
  console.log('SLO schema, exporter metrics and generated rules are current.');
} else fs.writeFileSync(destination, output);
