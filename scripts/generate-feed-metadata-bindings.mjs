#!/usr/bin/env node
// Generates typed feed metadata bindings from the canonical JSON schema.
// Output is deterministic (no timestamps). Use --check in CI to fail on drift.
// Usage: node scripts/generate-feed-metadata-bindings.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';

const SCHEMA = 'packages/sdk-bindings/schema/feed-metadata.schema.json';
const OUT = 'packages/sdk-bindings/src/generated/feedMetadata.ts';
const raw = readFileSync(SCHEMA, 'utf8');
const schema = JSON.parse(raw);
const hash = createHash('sha256').update(JSON.stringify(schema)).digest('hex').slice(0, 16);
const pascal = (s) => s[0].toUpperCase() + s.slice(1);

function tsType(p, name) {
  if (p.enum) return p.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (p.type === 'string') return 'string';
  if (p.type === 'integer' || p.type === 'number') return 'number';
  if (p.type === 'boolean') return 'boolean';
  if (p.type === 'array') {
    const t = tsType(p.items, name);
    return t.includes('|') ? `Array<${t}>` : `${t}[]`;
  }
  throw new Error(`unsupported schema type for ${name}: ${JSON.stringify(p)}`);
}

const required = new Set(schema.required ?? []);
const names = Object.keys(schema.properties);
const L = [];
L.push('// AUTO-GENERATED by scripts/generate-feed-metadata-bindings.mjs. DO NOT EDIT.');
L.push(`// Source: ${SCHEMA} (schema version ${schema['x-schemaVersion']}, sha256:${hash})`);
L.push('');
L.push(`export const FEED_METADATA_SCHEMA_VERSION = ${schema['x-schemaVersion']} as const;`);
L.push(`export const FEED_METADATA_SCHEMA_HASH = '${hash}' as const;`);
L.push('');
for (const n of names) {
  const p = schema.properties[n];
  if (p.enum) L.push(`export type ${pascal(n)} = ${tsType(p, n)};`);
}
L.push('');
L.push(`export interface ${schema.title} {`);
for (const n of names) {
  const p = schema.properties[n];
  if (p.description) L.push(`  /** ${p.description} */`);
  const t = p.enum ? pascal(n) : tsType(p, n);
  L.push(`  ${n}${required.has(n) ? '' : '?'}: ${t};`);
}
L.push('}');
L.push('');
L.push(`export const FEED_METADATA_FIELDS = ${JSON.stringify(names)} as const;`);
L.push(`export const FEED_METADATA_REQUIRED = ${JSON.stringify([...required])} as const;`);
L.push('');
L.push(`/** Runtime guard matching the schema constraints. */`);
L.push(`export function isFeedMetadata(v: unknown): v is ${schema.title} {`);
L.push(`  if (typeof v !== 'object' || v === null || Array.isArray(v)) return false;`);
L.push(`  const o = v as Record<string, unknown>;`);
L.push(`  for (const k of Object.keys(o)) if (!(FEED_METADATA_FIELDS as readonly string[]).includes(k)) return false;`);
L.push(`  for (const k of FEED_METADATA_REQUIRED) if (o[k] === undefined) return false;`);
for (const n of names) {
  const p = schema.properties[n];
  const c = [];
  if (p.enum) c.push(`${JSON.stringify(p.enum)}.includes(x as string)`);
  else if (p.type === 'string') c.push(`typeof x === 'string'`);
  else if (p.type === 'integer') {
    c.push(`Number.isInteger(x)`);
    if (p.minimum !== undefined) c.push(`(x as number) >= ${p.minimum}`);
    if (p.maximum !== undefined) c.push(`(x as number) <= ${p.maximum}`);
  } else if (p.type === 'array') {
    c.push(`Array.isArray(x)`);
    if (p.minItems) c.push(`(x as unknown[]).length >= ${p.minItems}`);
    if (p.items?.enum) c.push(`(x as unknown[]).every((i) => ${JSON.stringify(p.items.enum)}.includes(i as string))`);
  }
  L.push(`  { const x = o.${n}; if (x !== undefined && !(${c.join(' && ')})) return false; }`);
}
L.push(`  return true;`);
L.push('}');
L.push('');
const out = L.join('\n');

if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== out) {
    console.error(`${OUT} is out of date; run: node scripts/generate-feed-metadata-bindings.mjs`);
    process.exit(1);
  }
  console.log('feed metadata bindings up to date');
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}
